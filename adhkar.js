/* ============ 7. عرض قائمة الأذكار ============ */
function showAdhkarList(title, adhkarList, type) {
  var html = '<div class="picker-overlay" onclick="closeAdhkar(event)">';
  html += '<div class="picker-content" onclick="event.stopPropagation()" style="max-width:600px;max-height:85vh">';
  html += '<div class="picker-header">';
  html += '<h3>' + title + '</h3>';
  html += '<button class="picker-close" onclick="closeAdhkar()">✕</button>';
  html += '</div>';
  html += '<div class="settings-body" style="max-height:75vh;overflow-y:auto;padding:15px">';

  for (var i = 0; i < adhkarList.length; i++) {
    var zikr = adhkarList[i];
    html += '<div class="adhkar-item" style="background:rgba(255,215,0,0.05);border:1px solid rgba(255,215,0,0.2);border-radius:15px;padding:15px;margin-bottom:15px">';
    html += '<div style="color:#FFD700;font-size:18px;font-weight:700;margin-bottom:10px;display:flex;justify-content:space-between;align-items:center">';
    html += '<span>' + zikr.title + '</span>';
    html += '<span style="background:rgba(255,215,0,0.2);color:#FFD700;padding:3px 10px;border-radius:10px;font-size:12px">' + zikr.repeat + '</span>';
    html += '</div>';
    html += '<div style="font-family:Amiri Quran,serif;font-size:19px;line-height:2;color:#fff;text-align:right;padding:12px;background:rgba(0,0,0,0.2);border-radius:10px;margin-bottom:10px">';
    html += zikr.text.replace(/\n/g, '<br><br>');
    html += '</div>';
    if (zikr.virtue) {
      html += '<div style="color:#4CAF50;font-size:13px;padding:8px;background:rgba(76,175,80,0.1);border-radius:8px">';
      html += '✨ <b>الفضل:</b> ' + zikr.virtue;
      html += '</div>';
    }
    if (zikr.source) {
      html += '<div style="color:#aaa;font-size:12px;margin-top:8px;text-align:left">📚 ' + zikr.source + '</div>';
    }
    html += '</div>';
  }

  html += '</div></div></div>';
  document.body.insertAdjacentHTML("beforeend", html);
}

/* ============ 8. إغلاق ============ */
function closeAdhkar(e) {
  if (e && e.target !== e.currentTarget && !e.target.classList.contains("picker-close")) return;
  var el = document.querySelector(".picker-overlay");
  if (el) el.remove();
}

